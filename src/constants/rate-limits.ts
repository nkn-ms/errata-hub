// レート制限のしきい値。実装は src/lib/rate-limit.ts。
//
// なぜ要るか: 危ない入口はすべてログイン必須だが、認証が確認するのは「誰か」だけで
// 「何回まで」は見ていない。アカウントは無料で作れるので、1個作られた時点で守りが無くなる。
// 守りたいのは主に外部コストで、①Supabase Storage の容量（画像）②Google Books API の
// 無料枠（プロジェクト全体で共有＝1人が使い切ると全員が検索できなくなる）の2つ。
//
// 悪意が無くても効く: デバウンス（book-search.tsx）が改修で壊れる・リトライが暴走する等、
// 自分のバグに対する保険でもある。
//
// 値の考え方: 「まっとうな利用がぶつからない」ことを最優先にした緩めの設定。
// 絞り込みは実トラフィックを見てから行う（公開前の今は実測値が無いので当て推量になる）。
export const RATE_LIMITS = {
  // 投稿。熱心な投稿者でも1日10件は超えない見込み。
  // 画像の総量もここが天井になる（1投稿3枚 × 20 = 1日60枚 = 最大240MB）
  createReport: { limit: 20, windowSec: 24 * 60 * 60 },

  // 画像アップロード。上の投稿上限が日の天井を決めるので、これはバーストを均すだけの役割
  reportImageUpload: { limit: 30, windowSec: 60 * 60 },

  // 書籍検索（Google Books）。分の窓は 400ms デバウンスのタイプアヘッド用で、
  // 打ちながら検索しても通常はぶつからない。日の窓が無料枠（1,000/日・全体共有）の防波堤
  booksSearchPerMinute: { limit: 30, windowSec: 60 },
  booksSearchPerDay: { limit: 300, windowSec: 24 * 60 * 60 },

  // OpenBD 照会。1回の検索で書籍検索より多く飛ぶ（結果の書誌補正で最大20件をまとめて引く）ため緩め
  booksOpenbd: { limit: 60, windowSec: 60 },

  // 賛同。1人1票は @@unique で担保済みなのでリスクは低いが、連打での書き込みは抑える
  toggleUpvote: { limit: 60, windowSec: 60 },
} as const;
